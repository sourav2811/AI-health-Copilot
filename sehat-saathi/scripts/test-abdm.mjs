import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({stdin:{contents:"export * from './lib/health'; export * from './lib/abdm';",resolveDir:process.cwd(),loader:'ts'},bundle:true,write:false,platform:'node',format:'esm'});
const {toAbdmDraft,documentChecks,demoRecords}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const record=structuredClone(demoRecords[0]);
assert.throws(()=>toAbdmDraft({...record,reviewed:false}),/Review/);
const bundle=toAbdmDraft(record,true);
assert.equal(bundle.type,'document');
assert.equal(bundle.entry[0].resource.resourceType,'Composition');
assert.equal(bundle.entry[0].resource.status,'preliminary');
assert.ok(bundle.identifier.system&&bundle.identifier.value&&bundle.timestamp);
assert.equal(bundle.meta.profile,undefined,'Do not claim validated ABDM conformance');
assert.equal(bundle.entry.filter(e=>e.resource.resourceType==='Patient').length,1);
assert.ok(bundle.entry.some(e=>e.resource.resourceType==='Device'));
const urls=new Set(bundle.entry.map(e=>e.fullUrl));
assert.equal(urls.size,bundle.entry.length);
function refs(x){if(x&&typeof x==='object'){if('reference'in x)assert.ok(urls.has(x.reference));Object.values(x).forEach(refs);}}refs(bundle);
const real=toAbdmDraft({...record,synthetic:false},true);
assert.equal(real.entry.find(e=>e.resource.resourceType==='Patient').resource.identifier,undefined);
const text=toAbdmDraft({...record,title:'<script>alert("x")</script>'});
assert.ok(!text.entry[0].resource.text.div.includes('<script>'));
assert.equal(documentChecks({...record,date:'2026-02-31'}).find(c=>c.key==='date').passed,false);
assert.equal(documentChecks({...record,patientName:''}).find(c=>c.key==='patient').passed,false);
assert.equal(documentChecks(demoRecords[1]).find(c=>c.key==='uncertainty').passed,false);
console.log('PASS: ABDM draft review gate, document shape, identity separation, escaped narrative, reference integrity and honest conformance labels.');
